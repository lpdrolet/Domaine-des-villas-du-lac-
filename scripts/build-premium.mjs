import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {build} from "esbuild";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const dest=path.join(root,"dist");
fs.rmSync(dest,{recursive:true,force:true});fs.mkdirSync(dest,{recursive:true});
const files=fs.readdirSync(root).filter(s=>s.endsWith(".html")||s==="robots.txt"||s==="_redirects");
for(const f of files)fs.copyFileSync(path.join(root,f),path.join(dest,f));
fs.cpSync(path.join(root,"assets"),path.join(dest,"assets"),{recursive:true});
fs.mkdirSync(path.join(dest,"terrains"),{recursive:true});
const lotFiles=fs.readdirSync(path.join(root,"terrains")).filter(f=>f.endsWith(".html"));
for(const f of lotFiles)fs.copyFileSync(path.join(root,"terrains",f),path.join(dest,"terrains",f));
await build({entryPoints:{"admin.bundle":"client/admin-entry.js","client.bundle":"client/client-entry.js"},bundle:true,format:"esm",platform:"browser",target:["es2022"],outdir:path.join(dest,"assets"),minify:true,logLevel:"warning"});
const urls=["/","/projet.html","/carte.html","/terrains.html","/recapitulatif.html","/investisseurs.html","/contact.html",...lotFiles.map(f=>"/terrains/"+f)];
const site="https://domaine-des-villas-du-lac.netlify.app";
fs.writeFileSync(path.join(dest,"sitemap.xml"),'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+urls.map(u=>"<url><loc>"+site+u+"</loc></url>").join("\n")+"\n</urlset>\n");
for(const x of ["admin.bundle.js","client.bundle.js"])if(!fs.existsSync(path.join(dest,"assets",x)))throw Error("Bundle d'authentification absent : "+x);
if(lotFiles.length!==16)throw Error("16 fiches de terrain attendues");
console.log("Build Premium OK:",lotFiles.length,"fiches cadastrales;",urls.length,"URL publiques et 2 bundles Identity.");
